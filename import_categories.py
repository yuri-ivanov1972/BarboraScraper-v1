def normalize_to_slug(name_lv):
    lv_to_ascii = {
        'ā': 'a', 'č': 'c', 'ē': 'e', 'ģ': 'g', 'ī': 'i', 'ķ': 'k',
        'ļ': 'l', 'ņ': 'n', 'š': 's', 'ū': 'u', 'ž': 'z',
        'Ā': 'a', 'Č': 'c', 'Ē': 'e', 'Ģ': 'g', 'Ī': 'i', 'Ķ': 'k',
        'Ļ': 'l', 'Ņ': 'n', 'Š': 's', 'Ū': 'u', 'Ž': 'z',
    }
    result = name_lv.lower().strip()
    for lv_char, ascii_char in lv_to_ascii.items():
        result = result.replace(lv_char, ascii_char)
    result = unicodedata.normalize('NFKD', result).encode('ascii', 'ignore').decode('ascii')
    result = re.sub(r'[^a-z0-9\s-]', '', result)
    result = re.sub(r'[\s_]+', '-', result)
    result = re.sub(r'-+', '-', result)
    result = result.strip('-')
    return result

def get_translation(name_lv):
    name_clean = name_lv.strip()
    if name_clean in TRANSLATIONS:
        return TRANSLATIONS[name_clean]
    return name_clean

def main():
    csv_path = "attached_assets/barbora-categories-stored-2025-12-31_1767266940093.csv"
    
    categories = []
    uuid_to_seq = {}
    
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        seq_id = 0
        for row in reader:
            if row.get('Is Grocery', '').strip() != 'Yes':
                continue
            seq_id += 1
            uuid = row['ID'].strip()
            uuid_to_seq[uuid] = seq_id
            categories.append({
                'category_id': seq_id,
                'barbora_category_code': uuid,
                'name_lv': row['Name'].strip(),
                'parent_uuid': row['Parent ID'].strip() if row['Parent ID'].strip() else None,
                'level': int(row['Level'].strip())
            })
    
    for cat in categories:
        cat['name_en'] = get_translation(cat['name_lv'])
        cat['normalized_category'] = normalize_to_slug(cat['name_lv'])
        if cat['parent_uuid']:
            cat['parent_category_id'] = uuid_to_seq.get(cat['parent_uuid'])
        else:
            cat['parent_category_id'] = None
    
    conn = psycopg2.connect(os.environ['DATABASE_URL'])
    cur = conn.cursor()
    
    cur.execute("DELETE FROM normalized_categories")
    
